#include "hlsl_codegen.h"
#include <sstream>

namespace khanary::klsl {

std::string HLSLCodegen::glyph_hlsl(
    GlyphOp op,
    const std::string& result,
    const std::vector<std::string>& operands)
{
    auto op0 = operands.empty() ? "buf" : operands[0];
    auto op1 = operands.size() > 1 ? operands[1] : "buf";
    auto op2 = operands.size() > 2 ? operands[2] : "buf";

    switch (op) {
        case GlyphOp::MATMUL:
            return "    float " + result + " = dot(" + op0 + "[tid.x], " + op1 + "[tid.x]);";
        case GlyphOp::CONV:
            return "    float " + result + " = " + op0 + "[tid.x] * " + op1 + "[0];";
        case GlyphOp::ATTN:
            return "    float " + result + "_score = dot(" + op0 + "[tid.x], " + op1 + "[tid.x]) * 0.125f;";
        case GlyphOp::SOFTMAX:
            return "    float " + result + " = exp(" + op0 + "[tid.x]) / 1.0f; // simplified softmax";
        case GlyphOp::AFFINE:
            return "    float " + result + " = " + op0 + "[tid.x] * " + op1 + "[0] + " + op2 + "[0];";
        case GlyphOp::COMPRESS:
            return "    uint  " + result + " = asuint(" + op0 + "[tid.x]);";
        case GlyphOp::SPHERICAL:
            return "    float " + result + " = sin(length(float2(" + op0 + "[tid.x], " + op0 + "[tid.x+1])));";
        case GlyphOp::TORSION:
            return "    float " + result + " = " + op0 + "[tid.x] - " + op0 + "[max(0,(int)tid.x-1)];";
        case GlyphOp::RADIAL:
            return "    float " + result + " = length(float2(" + op0 + "[tid.x], (float)tid.x));";
        case GlyphOp::WAVE:
            return "    float " + result + " = sin((float)tid.x * 0.1f) * " + op0 + "[tid.x];";
        default:
            return "    // NOP";
    }
}

std::string HLSLCodegen::emit_header(const IRFunction& fn, uint32_t gx, uint32_t gy) {
    std::ostringstream ss;
    ss << "// KHANARY HLSL — " << fn.name << "\n";
    ss << "// Auto-generated by KLSL hlsl_codegen\n\n";
    // Declare buffers for each param
    uint32_t slot = 0;
    for (const auto& p : fn.params) {
        ss << "StructuredBuffer<float> " << p << " : register(t" << slot++ << ");\n";
    }
    // UAV output buffers for non-param values
    slot = 0;
    for (const auto& [name, val] : fn.values) {
        if (!val.is_param)
            ss << "RWStructuredBuffer<float> " << name << " : register(u" << slot++ << ");\n";
    }
    ss << "\n[numthreads(" << gx << ", " << gy << ", 1)]\n";
    ss << "void main(uint3 tid : SV_DispatchThreadID, uint3 gid : SV_GroupThreadID)\n{\n";
    return ss.str();
}

std::string HLSLCodegen::emit_instruction(const IRInstruction& ins) {
    return glyph_hlsl(ins.op, ins.result, ins.operands) + "\n";
}

std::string HLSLCodegen::emit_body(const IRFunction& fn) {
    std::ostringstream ss;
    for (const auto& blk : fn.blocks) {
        if (!blk.name.empty() && blk.name != "entry")
            ss << "    // --- phase: " << blk.name << " ---\n";
        for (const auto& ins : blk.instructions)
            ss << emit_instruction(ins);
    }
    return ss.str();
}

std::string HLSLCodegen::emit(const IRFunction& fn, uint32_t gx, uint32_t gy) {
    return emit_header(fn, gx, gy) + emit_body(fn) + "}\n";
}

std::string HLSLCodegen::emit_module(const IRModule& mod) {
    std::string out;
    for (const auto& fn : mod.functions)
        out += emit(fn) + "\n\n";
    return out;
}

} // namespace khanary::klsl
