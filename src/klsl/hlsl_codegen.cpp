static std::string trim_copy(const std::string& s) {
    const size_t a = s.find_first_not_of(" \t\r\n");
    if (a == std::string::npos) return "";
    const size_t b = s.find_last_not_of(" \t\r\n");
    return s.substr(a, b - a + 1);
}

static bool is_ident_start(unsigned char c) {
    return std::isalpha(c) || c == '_';
}

static bool is_ident_continue(unsigned char c) {
    return std::isalnum(c) || c == '_';
}

static bool is_identifier(const std::string& raw) {
    const std::string s = trim_copy(raw);
    if (s.empty()) return false;
    if (!is_ident_start(static_cast<unsigned char>(s[0]))) return false;
    for (size_t i = 1; i < s.size(); ++i) {
        if (!is_ident_continue(static_cast<unsigned char>(s[i]))) return false;
    }
    return true;
}

static bool is_unsigned_int_literal(const std::string& raw) {
    const std::string s = trim_copy(raw);
    if (s.empty()) return false;
    for (unsigned char c : s) {
        if (!std::isdigit(c)) return false;
    }
    return true;
}

static bool is_number_literal(const std::string& raw) {
    const std::string s = trim_copy(raw);
    if (s.empty()) return false;
    bool seen_digit = false;
    bool seen_dot = false;
    size_t i = 0;
    if (s[0] == '+' || s[0] == '-') i = 1;
    for (; i < s.size(); ++i) {
        const unsigned char c = static_cast<unsigned char>(s[i]);
        if (std::isdigit(c)) {
            seen_digit = true;
            continue;
        }
        if (c == '.' && !seen_dot) {
            seen_dot = true;
            continue;
        }
        return false;
    }
    return seen_digit;
}

static bool is_member_expr(const std::string& raw) {
    const std::string s = trim_copy(raw);
    const size_t dot = s.find('.');
    if (dot == std::string::npos) return false;
    if (dot == 0 || dot + 1 >= s.size()) return false;
    if (s.find('.', dot + 1) != std::string::npos) return false;
    return is_identifier(s.substr(0, dot)) && is_identifier(s.substr(dot + 1));
}

static std::string sanitize_symbol(const std::string& raw, const std::string& fallback) {
    return is_identifier(raw) ? trim_copy(raw) : fallback;
}

static std::string sanitize_expr_atom(const std::string& raw, const std::string& fallback) {
    if (is_identifier(raw) || is_number_literal(raw) || is_member_expr(raw)) return trim_copy(raw);
    return fallback;
}

static std::string sanitize_index_expr(const std::string& raw, const std::string& fallback) {
    if (is_identifier(raw) || is_unsigned_int_literal(raw) || is_member_expr(raw)) return trim_copy(raw);
    return fallback;
}

static std::string sanitize_label_token(const std::string& raw, const std::string& fallback) {
    if (is_identifier(raw) || is_unsigned_int_literal(raw)) return trim_copy(raw);
    return fallback;
}

static bool is_explicit_control_target(const std::string& raw) {
    return is_identifier(raw) || is_unsigned_int_literal(raw);
}

