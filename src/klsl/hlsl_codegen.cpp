std::string HLSLCodegen::glyph_hlsl(
    GlyphOp op,
    const std::string& result,
    const std::vector<std::string>& operands)
{
    auto op0 = operands.empty() ? "buf" : operands[0];
    auto op1 = operands.size() > 1 ? operands[1] : "buf";
    auto op2 = operands.size() > 2 ? operands[2] : "buf";

    switch (op) {
        case GlyphOp::MATMUL:
            return "    float " + result + " = dot(" + op0 + "[tid.x], " + op1 + "[tid.x]);";
        case GlyphOp::CONV:
            return "    float " + result + " = " + op0 + "[tid.x] * " + op1 + "[0];";
        case GlyphOp::ATTN:
            return "    float " + result + "_score = dot(" + op0 + "[tid.x], " + op1 + "[tid.x]) * 0.125f;";
        case GlyphOp::SOFTMAX:
            return "    float " + result + " = exp(" + op0 + "[tid.x]) / 1.0f; // simplified softmax";
        case GlyphOp::AFFINE:
            return "    float " + result + " = " + op0 + "[tid.x] * " + op1 + "[0] + " + op2 + "[0];";
        case GlyphOp::COMPRESS:
            return "    uint  " + result + " = asuint(" + op0 + "[tid.x]);";
        case GlyphOp::SPHERICAL:
            return "    float " + result + " = sin(length(float2(" + op0 + "[tid.x], " + op0 + "[tid.x+1])));";
        case GlyphOp::TORSION:
            return "    float " + result + " = " + op0 + "[tid.x] - " + op0 + "[max(0,(int)tid.x-1)];";
        case GlyphOp::RADIAL:
            return "    float " + result + " = length(float2(" + op0 + "[tid.x], (float)tid.x));";
        case GlyphOp::WAVE:
            return "    float " + result + " = sin((float)tid.x * 0.1f) * " + op0 + "[tid.x];";
        default:
            return "    // NOP";
    }
}

std::string HLSLCodegen::emit_header(const IRFunction& fn, uint32_t gx, uint32_t gy) {
    std::ostringstream ss;
    ss << "// KHANARY HLSL — " << fn.name << "\n";
    ss << "// Auto-generated by KLSL hlsl_codegen\n\n";
    ss << "// Control flow is emitted only from explicit KLSL control opcodes.\n";
    ss << "// Semantic-fold similarity tokens are treated as data, not branch authority.\n\n";
    // Declare buffers for each param
    uint32_t slot = 0;
    for (const auto& p : fn.params) {
        ss << "StructuredBuffer<float> " << p << " : register(t" << slot++ << ");\n";
    }
    // UAV output buffers for non-param values
    slot = 0;
    for (const auto& [name, val] : fn.values) {
        if (!val.is_param)
            ss << "RWStructuredBuffer<float> " << name << " : register(u" << slot++ << ");\n";
    }
    ss << "\n[numthreads(" << gx << ", " << gy << ", 1)]\n";
    ss << "void main(uint3 tid : SV_DispatchThreadID, uint3 groupId : SV_GroupID, uint3 lid : SV_GroupThreadID)\n{\n";
    return ss.str();
}

std::string HLSLCodegen::emit_instruction(const IRInstruction& ins) {
    return glyph_hlsl(ins.op, ins.result, ins.operands) + "\n";
}

std::string HLSLCodegen::emit_body(const IRFunction& fn) {
    std::ostringstream ss;
    for (const auto& blk : fn.blocks) {
        if (!blk.name.empty() && blk.name != "entry")
            ss << "    // --- phase: " << blk.name << " ---\n";
        for (const auto& ins : blk.instructions)
            ss << emit_instruction(ins);
    }
    return ss.str();
}

std::string HLSLCodegen::emit(const IRFunction& fn, uint32_t gx, uint32_t gy) {
    return emit_header(fn, gx, gy) + emit_body(fn) + "}\n";
}

std::string HLSLCodegen::emit_module(const IRModule& mod) {
    std::string out;
    for (const auto& fn : mod.functions)
        out += emit(fn) + "\n\n";
    return out;
}

std::string HLSLCodegen::emit_wcr_score_expr(const std::string& result,
                                             const std::string& static_weight_expr,
                                             const std::string& confidence_expr,
                                             const std::string& relevance_expr) {
    const std::string dst = sanitize_symbol(result, "wcr_score");
    const std::string w = sanitize_expr_atom(static_weight_expr, "0.0");
    const std::string c = sanitize_expr_atom(confidence_expr, "0.0");
    const std::string r = sanitize_expr_atom(relevance_expr, "0.0");
    return "    float " + dst + " = saturate((" + w + ") * (" + c + ") * (" + r + "));";
}

// -----------------------------------------------------------------------
// KLSLOp → HLSL statement
// Operands: op0=a-reg, op1=b-reg, op2=c-reg (SSA names or "r<N>" strings)
// -----------------------------------------------------------------------
std::string HLSLCodegen::emit_klsl_instr(
    KLSLOp op,
    const std::string& result,
    const std::vector<std::string>& operands)
{
    const std::string raw_r0 = result;
    const std::string raw_a  = operands.size() > 0 ? operands[0] : "r0";
    const std::string raw_b  = operands.size() > 1 ? operands[1] : "r1";
    const std::string raw_c  = operands.size() > 2 ? operands[2] : "r2";

    const std::string r0 = sanitize_symbol(raw_r0, "r0");
    const std::string a_expr = sanitize_expr_atom(raw_a, "0");
    const std::string b_expr = sanitize_expr_atom(raw_b, "0");
    const std::string c_expr = sanitize_expr_atom(raw_c, "0");
    const std::string a_idx = sanitize_index_expr(raw_a, "0");
    const std::string r0_idx = sanitize_index_expr(raw_r0, "0");

    switch (op) {
        // ---- NOP / control ----
        case OP_NOP:          return "    // nop";
        case OP_RET:          return "    return;";
        case OP_RET_V:        return "    return " + a_expr + ";";
        case OP_JMP: {
            if (!is_explicit_control_target(raw_a))
                return "    // blocked unsafe jump target";
            return "    goto lbl_" + sanitize_label_token(raw_a, "0") + ";";
        }
        case OP_JZ: {
            if (!is_explicit_control_target(raw_a))
                return "    // blocked unsafe jump target";
            return "    if (" + b_expr + " == 0) goto lbl_" + sanitize_label_token(raw_a, "0") + ";";
        }
        case OP_JNZ: {
            if (!is_explicit_control_target(raw_a))
                return "    // blocked unsafe jump target";
            return "    if (" + b_expr + " != 0) goto lbl_" + sanitize_label_token(raw_a, "0") + ";";
        }
        case OP_CALL: {
            const std::string fn_name = sanitize_symbol(raw_a, "");
            if (fn_name.empty()) return "    // blocked unsafe call target";
            return "    " + r0 + " = " + fn_name + "();";
        }

        // ---- Register / immediate ----
        case OP_LOAD_IMMU: {
            const std::string imm = is_unsigned_int_literal(raw_a) ? trim_copy(raw_a) : "0";
            return "    uint " + r0 + " = " + imm + "u;";
        }
        case OP_LOAD_CONST:   return "    float " + r0 + " = _const[" + a_idx + "];";
        case OP_MOV:          return "    " + r0 + " = " + a_expr + ";";
        case OP_ZERO:         return "    " + r0 + " = 0;";

        // ---- Integer arithmetic ----
        case OP_IADD:         return "    int " + r0 + " = " + a_expr + " + " + b_expr + ";";
        case OP_ISUB:         return "    int " + r0 + " = " + a_expr + " - " + b_expr + ";";
        case OP_IMUL:         return "    int " + r0 + " = " + a_expr + " * " + b_expr + ";";
        case OP_IDIV:         return "    int " + r0 + " = " + a_expr + " / " + b_expr + ";";
        case OP_IMOD:         return "    int " + r0 + " = " + a_expr + " % " + b_expr + ";";
        case OP_INEG:         return "    int " + r0 + " = -" + a_expr + ";";
        case OP_IABS:         return "    int " + r0 + " = abs(" + a_expr + ");";
        case OP_ILT:          return "    int " + r0 + " = (" + a_expr + " < "  + b_expr + ") ? 1 : 0;";
        case OP_ILE:          return "    int " + r0 + " = (" + a_expr + " <= " + b_expr + ") ? 1 : 0;";
        case OP_IGT:          return "    int " + r0 + " = (" + a_expr + " > "  + b_expr + ") ? 1 : 0;";
        case OP_IEQ:          return "    int " + r0 + " = (" + a_expr + " == " + b_expr + ") ? 1 : 0;";

        // ---- Float arithmetic ----
        case OP_FADD:         return "    float " + r0 + " = " + a_expr + " + " + b_expr + ";";
        case OP_FSUB:         return "    float " + r0 + " = " + a_expr + " - " + b_expr + ";";
        case OP_FMUL:         return "    float " + r0 + " = " + a_expr + " * " + b_expr + ";";
        case OP_FDIV:         return "    float " + r0 + " = " + a_expr + " / " + b_expr + ";";
        case OP_FMAD:         return "    float " + r0 + " = fma(" + a_expr + ", " + b_expr + ", " + c_expr + ");";
        case OP_FNEG:         return "    float " + r0 + " = -" + a_expr + ";";
        case OP_FABS:         return "    float " + r0 + " = abs(" + a_expr + ");";
        case OP_FSQRT:        return "    float " + r0 + " = sqrt(" + a_expr + ");";
        case OP_FMAX:         return "    float " + r0 + " = max(" + a_expr + ", " + b_expr + ");";
        case OP_FMIN:         return "    float " + r0 + " = min(" + a_expr + ", " + b_expr + ");";
        case OP_RELU:         return "    float " + r0 + " = max(" + a_expr + ", 0.f);";
        case OP_FLT:          return "    float " + r0 + " = (" + a_expr + " < " + b_expr + ") ? 1.f : 0.f;";
        case OP_FEQ:          return "    float " + r0 + " = (" + a_expr + " == " + b_expr + ") ? 1.f : 0.f;";

        // ---- Transcendentals ----
        case OP_FSIN:         return "    float " + r0 + " = sin(" + a_expr + ");";
        case OP_FCOS:         return "    float " + r0 + " = cos(" + a_expr + ");";
        case OP_FTAN:         return "    float " + r0 + " = tan(" + a_expr + ");";
        case OP_FEXP:         return "    float " + r0 + " = exp(" + a_expr + ");";
        case OP_FLOG:         return "    float " + r0 + " = log(" + a_expr + ");";
        case OP_FLOG2:        return "    float " + r0 + " = log2(" + a_expr + ");";
        case OP_FPOW:         return "    float " + r0 + " = pow(" + a_expr + ", " + b_expr + ");";

        // ---- Shared memory ----
        case OP_LOAD_SHARED:  return "    float " + r0 + " = _shared[" + a_idx + "];";
        case OP_STORE_SHARED: return "    _shared[" + r0_idx + "] = " + a_expr + ";";
        case OP_LOAD_IN0:     return "    float " + r0 + " = in0[" + a_idx + "];";
        case OP_LOAD_IN1:     return "    float " + r0 + " = in1[" + a_idx + "];";
        case OP_LOAD_IN2:     return "    float " + r0 + " = in2[" + a_idx + "];";
        case OP_STORE_OUT0:   return "    out0[" + r0_idx + "] = " + a_expr + ";";
        case OP_STORE_OUT1:   return "    out1[" + r0_idx + "] = " + a_expr + ";";

        // ---- Atomics ----
        case OP_ATOMIC_ADD:   return "    InterlockedAdd(_shared[" + r0_idx + "], " + a_expr + ", " + b_expr + ");";
        case OP_ATOMIC_MAX:   return "    InterlockedMax(_shared[" + r0_idx + "], " + a_expr + ", " + b_expr + ");";
        case OP_ATOMIC_MIN:   return "    InterlockedMin(_shared[" + r0_idx + "], " + a_expr + ", " + b_expr + ");";
        case OP_ATOMIC_CAS:   return "    InterlockedCompareExchange(_shared[" + r0_idx + "], " + a_expr + ", " + b_expr + ", " + r0 + ");";

        // ---- Thread / dispatch ----
        case OP_THREAD_ID:    return "    uint " + r0 + " = tid.x;";
        case OP_THREAD_CNT:   return "    uint " + r0 + " = _thread_count;";
        case OP_GROUP_ID:     return "    uint " + r0 + " = groupId.x;";
        case OP_LOCAL_ID:     return "    uint " + r0 + " = lid.x;";
        case OP_BARRIER:      return "    GroupMemoryBarrierWithGroupSync();";
        case OP_SPAWN:        return "    // spawn " + sanitize_symbol(raw_a, "subkernel");

        default: {
            std::ostringstream oss;
            oss << "    // unknown klsl op 0x" << std::hex
                << static_cast<unsigned>(static_cast<uint8_t>(op));
            return oss.str();
        }
    }
}

